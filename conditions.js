// 1. Declare and initialize a number
let number = 8;

// 2. Check if the number is positive, negative, or zero
if (number > 0) {
    console.log(number + " is positive");
} else if (number < 0) {
    console.log(number + " is negative");
} else {
    console.log(number + " is zero");
}
