// Exercise 1: Working with Variables and Data Types

// 1. Declare and initialize variables
let name = "Bahati Chiruwa";
let age = 26;
let isStudent = false;
let address = {
    city: "Nairobi",
    country: "Kenya"
};
let hobbies = ["coding", "researching", "driving"];
let undefinedVariable;
let nullVariable = null;

// 2. Print each variable's value and type
console.log("Name:", name, "- Type:", typeof name);
console.log("Age:", age, "- Type:", typeof age);
console.log("Is Student:", isStudent, "- Type:", typeof isStudent);
console.log("Address:", address, "- Type:", typeof address);
console.log("Hobbies:", hobbies, "- Type:", typeof hobbies);
console.log("Undefined Variable:", undefinedVariable, "- Type:", typeof undefinedVariable);
console.log("Null Variable:", nullVariable, "- Type:", typeof nullVariable);
